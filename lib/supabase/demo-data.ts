// Ventas de ejemplo (últimos 12 días, incluyendo hoy).
const sales: DemoRow[] = [];
const sale_items: DemoRow[] = [];
const payments: DemoRow[] = [];
const PRICE: Record<string, Record<string, number>> = {
  p1: { [B1]: 1.5, [B2]: 1.5 },
  p2: { [B1]: 1.5, [B2]: 1.5 },
  p4: { [B1]: 45, [B2]: 45 },
  p5: { [B1]: 3, [B2]: 3.5 },
  p8: { [B1]: 4.5, [B2]: 4.5 },
  p9: { [B1]: 5, [B2]: 5.5 },
  p11: { [B1]: 2, [B2]: 2 },
};
const sellable = Object.keys(PRICE);
for (let i = 0; i < 22; i++) {
  const branch = i % 2 === 0 ? B1 : B2;
  const product = sellable[i % sellable.length];
  const price = PRICE[product][branch];
  const qty = (i % 3) + 1;
  const total = Math.round(price * qty * 100) / 100;
  const day = i < 5 ? 0 : i - 4; // varias ventas hoy
  const created = daysAgo(day % 12, 9 + (i % 8));
  const saleId = `sale-${i + 1}`;
  sales.push({
    id: saleId,
    branch_id: branch,
    serie: branch === B1 ? "B001" : "B002",
    numero: i + 1,
    customer_id: null,
    cashier_id: i % 3 === 0 ? U2 : U1,
    subtotal: total,
    descuento: 0,
    igv: 0,
    total,
    tipo_consumo: i % 4 === 0 ? "PARA_LLEVAR" : "LOCAL",
    status: "COMPLETADA",
    notas: null,
    created_at: created,
    updated_at: created,
  });
  sale_items.push({
    id: `si-${i + 1}`,
    sale_id: saleId,
    product_id: product,
    variant_id: null,
    cantidad: qty,
    precio_unitario: price,
    descuento: 0,
    subtotal: total,
  });
  payments.push({
    id: `pay-${i + 1}`,
    sale_id: saleId,
    method: i % 3 === 0 ? "YAPE" : "EFECTIVO",
    amount: total,
    referencia: null,
    created_at: created,
  });
}

